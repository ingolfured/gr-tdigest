"""Independent exact-rational reference checks; invoked only by an approved run."""

from __future__ import annotations

from fractions import Fraction
import math
import struct


def rational(value):
    return Fraction.from_float(float(value))


def type7(samples, q):
    """Exact rational interpolation, independently of the Rust float formula."""
    position = rational(q) * (len(samples) - 1)
    left = position.numerator // position.denominator
    fraction = position - left
    return (
        rational(samples[left]) * (1 - fraction)
        + rational(samples[min(left + 1, len(samples) - 1)]) * fraction
    )


def interval(samples, x):
    """Linear exact counts, independently of the Rust binary partition search."""
    return Fraction(sum(v < x for v in samples), len(samples)), Fraction(
        sum(v <= x for v in samples), len(samples)
    )


def rank_error(samples, q, x):
    lo, hi = interval(samples, x)
    return max(lo - rational(q), rational(q) - hi, Fraction(0))


def close_to_rational(actual, expected, probability=False, extra_tolerance=0.0):
    target = float(expected)
    tolerance = max(
        extra_tolerance,
        4 * math.ulp(1.0)
        if probability
        else 4 * max(math.ulp(target), math.ulp(actual)),
    )
    assert math.isfinite(actual) and abs(actual - target) <= tolerance, (
        actual,
        target,
        tolerance,
    )


def verify_manual_oracle():
    """Hand-computed gold values, not values generated by the harness under test."""
    assert type7([1, 2], 0.25) == Fraction(5, 4)
    assert type7([0, 0, 10, 10], 0.5) == 5
    assert type7([-4, -2, 0, 2, 4], 0.25) == -2
    assert type7([0, 2**-24, 1], 0.5) == Fraction(1, 2**24)
    assert type7([16777216, 16777216, 16777218], 0.5) == 16777216
    assert interval([0, 0, 10, 10], 0) == (0, Fraction(1, 2))
    assert interval([0, 0, 10, 10], 5) == (Fraction(1, 2), Fraction(1, 2))
    assert sum(interval([0, 0, 10, 10], 0)) / 2 == Fraction(1, 4)
    assert sum(interval([0, 0, 10, 10], 10)) / 2 == Fraction(3, 4)
    assert rank_error([0, 0, 10, 10], 0.25, 0) == 0
    assert rank_error([0, 0, 10, 10], 0.75, 0) == Fraction(1, 4)
    assert rank_error([0, 0, 10, 10], 0.5, 5) == 0
    assert rank_error([3, 3, 3], 0.25, 3) == 0
    assert sum(interval([3, 3, 3], 3)) / 2 == Fraction(1, 2)
    return {"status": "pass", "hand_computed_checks": 14}


FIXTURES = {
    "singleton": [1.0],
    "two": [1.0, 2.0],
    "ties": [0.0, 0.0, 10.0, 10.0],
    "negative": [-4.0, -2.0, 0.0, 2.0, 4.0],
    "adjacent_scale": [0.0, 2**-24, 1.0],
    "f32_collision": [16777216.0, 16777216.0, 16777218.0],
    "all_equal": [3.0, 3.0, 3.0],
}


def verify_reference_probe(rows):
    assert len(rows) == len(FIXTURES)
    assert {row["fixture"] for row in rows} == set(FIXTURES)
    count = 0
    for row in rows:
        samples = FIXTURES[row["fixture"]]
        assert row["samples"] == samples
        assert (
            len(row["quantile"]) == 5
            and len(row["cdf"]) == 13
            and len(row["rank"]) == 65
        )
        for q, observed in row["quantile"]:
            close_to_rational(observed, type7(samples, q))
            count += 1
        for x, lo, hi, midpoint in row["cdf"]:
            a, b = interval(samples, x)
            close_to_rational(lo, a, probability=True)
            close_to_rational(hi, b, probability=True)
            close_to_rational(midpoint, (a + b) / 2, probability=True)
            count += 3
        for q, x, observed in row["rank"]:
            close_to_rational(observed, rank_error(samples, q, x), probability=True)
            count += 1
    return {"status": "pass", "fixtures": len(rows), "numeric_cells_checked": count}


def verify_tiny_row(row):
    """Validate every emitted tiny-case reference without assuming core accuracy."""
    samples = row["reference_samples"]
    assert len(samples) == row["n"] <= 32 and samples == sorted(samples)
    checked = 0
    for requested, effective, estimate, reference, rank, error in row["state"][
        "quantile"
    ]["rows"]:
        expected_q = (
            struct.unpack("f", struct.pack("f", requested))[0]
            if row["precision"] == "f32"
            else requested
        )
        assert effective == expected_q
        # The Rust reference rounds q*(n-1) before interpolation. Bound that
        # position rounding and local cancellation, while the oracle remains
        # exact rational arithmetic on the supplied binary input numbers.
        position = effective * (len(samples) - 1)
        index = int(position)
        local = samples[max(0, index - 1) : min(len(samples), index + 3)]
        gap = max((abs(b - a) for a, b in zip(local, local[1:])), default=0.0)
        scale = max(map(abs, local))
        tolerance = 4 * math.ulp(position) * gap + 8 * math.ulp(scale)
        close_to_rational(
            reference, type7(samples, effective), extra_tolerance=tolerance
        )
        checked += 2
        # A nonfinite inherited old estimate is kept as an observation, not
        # replaced or silently excluded from the captured dataset.
        if estimate is not None and math.isfinite(estimate):
            close_to_rational(
                rank, rank_error(samples, effective, estimate), probability=True
            )
            assert error == abs(estimate - reference)
            checked += 2
    if row["core"] == "modern":
        for x, estimate, reference, error in row["state"]["cdf"]["rows"]:
            lo, hi = interval(samples, x)
            close_to_rational(reference, (lo + hi) / 2, probability=True)
            if estimate is not None:
                assert error == abs(estimate - reference)
            checked += 2
    return checked
